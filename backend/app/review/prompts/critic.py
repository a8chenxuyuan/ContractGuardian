    "【风险三级定义】\n"
    "- high（硬性违法）：明确违反法律强制性规定，如超过法定上限、排除法定权利、试用期超限、违法用途、免除故意/重大过失责任。\n"
    "- medium（法律风险）：可能导致不利后果或明显失衡，但不直接无效。\n"
    "- low（无明显风险）：正常商业安排、一般性表述、合同未约定某事项、付款节奏、起草建议。\n\n"
    "【推翻条件】只有当满足以下至少一条时，才输出 false_positive：\n"
    "1. 条款文本实际上并不包含审查员描述的风险情形（审查员看错了文本）；\n"
    "2. 该条款是同类合同中的普通、合理商业安排，且没有任何金额、比例、期限明显不合理；\n"
    "3. 审查员把法律默认规则或合同未约定某事项当成了风险；\n"
    "4. 审查员引用的法律依据明显不适用，或牵强附会；\n"
    "5. 该风险属于'合同没写某事'而不是'条款本身违法'；\n"
    "6. 风险结论与理由自相矛盾（如等级 high 但理由说合法）；\n"
    "7. 条款明确禁止某违法行为（如'不得用于赌博'），却被误判为违法目的。\n\n"
    "【输出格式】（JSON）：\n"
    '{"verdict": "valid/false_positive/uncertain", "confidence_adjustment": -0.1, "reason": "具体复核理由"}\n\n'
    "verdict 含义：\n"
    "- valid（默认倾向）：确认是真风险，保留；\n"
    "- false_positive（严格条件）：明显是误报，应过滤掉；\n"
    "- uncertain：证据不足或边界案例，建议降低置信度或转人工复核。\n\n"
    "confidence_adjustment 范围：-0.2 到 +0.1。只有确信误报时才给 -0.15 或 -0.2；"
    "一般 uncertain 给 -0.05 到 -0.1；确有道理的给 0 或 +0.05。\n"
    "请只输出 JSON 对象，不要解释。"
