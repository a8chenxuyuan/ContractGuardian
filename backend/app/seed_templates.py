async def seed_preset_templates(db: AsyncSession) -> int:
    """幂等播种预置范本：按 name+is_preset 查重。返回新插入条数。"""
    inserted = 0
    for tpl in PRESET_TEMPLATES:
        exists = (
            await db.execute(
                select(ContractTemplate.id).where(
                    ContractTemplate.name == tpl["name"],
                    ContractTemplate.is_preset.is_(True),
                )
            )
        ).scalar_one_or_none()
        if exists:
            continue
        db.add(ContractTemplate(**tpl, is_preset=True, usage_count=0))
        inserted += 1
    if inserted:
        await db.commit()
    return inserted
